const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const root=path.join(__dirname,'..');
const model=fs.readFileSync(path.join(root,'src/model.js'),'utf8').replace(/export /g,'');
const tags=fs.readFileSync(path.join(root,'src/tags.js'),'utf8').replace(/export /g,'');
const preview=fs.readFileSync(path.join(root,'src/undoPreview.js'),'utf8')
  .replace(/^import .*;\s*$/gm,'').replace(/export /g,'');
const ctx={};vm.createContext(ctx);
vm.runInContext(model+'\n'+tags+'\n'+preview+'\nthis.api={describeUndo,historyAfterTagRename};',ctx);
const {describeUndo,historyAfterTagRename}=ctx.api;
const source='content://provider/tree/primary%3APictures%2FScreenshots';
const destination='content://provider/tree/primary%3APictures%2FPole%20Tricks';
const move={type:'move',name:'photo.jpg',toUri:'content://dst/photo.jpg',toDirUri:destination,sourceUri:source};
const moveInfo=describeUndo(move,source);
assert.equal(moveInfo.title,'Undo move');
assert(moveInfo.description.includes('Pictures/Pole Tricks'));
assert(moveInfo.description.includes('Pictures/Screenshots'));
assert.equal(moveInfo.thumbnailUri,move.toUri);
assert.equal(moveInfo.isImage,true);
const copyInfo=describeUndo({...move,type:'copy'},source);
assert.match(copyInfo.description,/Remove the copied file/);
assert.match(copyInfo.description,/stays untouched/);
const deleteInfo=describeUndo({type:'delete',name:'cat.png',toUri:'file://private/recycle/cat',sourceUri:source},source);
assert.equal(deleteInfo.thumbnailUri,'file://private/recycle/cat');
const cropInfo=describeUndo({type:'crop',name:'pic.png',sourceUri:'content://img',sourceDirUri:source,backupUri:'file://backup'},source);
assert.equal(cropInfo.thumbnailUri,'file://backup');
assert.match(cropInfo.description,/original uncropped image/);
const cutInfo=describeUndo({type:'cut',name:'VID.mp4',sourceDirUri:source,backupUri:'file://oldvideo'},source);
assert.equal(cutInfo.isVideo,true);
assert.equal(cutInfo.thumbnailUri,'file://oldvideo');
const renameInfo=describeUndo({type:'rename',oldName:'before.jpg',newName:'after.jpg',sourceDirUri:source,afterUri:'content://after'},source);
assert.match(renameInfo.description,/after.jpg.*before.jpg/);
const old={type:'rename',oldName:'a.jpg',newName:'b.jpg',afterUri:'content://before',sourceDirUri:source};
const history=[old,{type:'move',name:'elsewhere.png',toUri:'content://other'}];
const tagged=historyAfterTagRename(history,{name:'b.jpg',uri:'content://before'},{name:'b [Pole].jpg',uri:'content://after'},'[Pole]',source);
assert.equal(tagged.length,2,'Tag adds NO undo operation');
assert.equal(tagged[0].oldName,'a [Pole].jpg','tag preserved on old name for later rename undo');
assert.equal(tagged[0].newName,'b [Pole].jpg');
assert.equal(tagged[0].afterUri,'content://after');
assert.equal(tagged[1].toUri,'content://other');
assert.equal(old.oldName,'a.jpg','input history remains untouched');
const untagged=historyAfterTagRename(tagged,{name:'b [Pole].jpg',uri:'content://after'},{name:'b.jpg',uri:'content://before'},'[Pole]',source);
assert.equal(untagged[0].oldName,'a.jpg');
assert.equal(untagged[0].newName,'b.jpg');
const demoHistory=historyAfterTagRename([{type:'demoRename',oldName:'a.jpg',at:2}],{name:'b.jpg',uri:'demo',at:2},{name:'b [Pole].jpg',uri:'demo'},'[Pole]');
assert.equal(demoHistory[0].oldName,'a [Pole].jpg');
const oldCrop={type:'crop',name:'a.jpg',sourceUri:source,backupUri:'file://old'};
const corrected=historyAfterTagRename([oldCrop],{name:'a.jpg',uri:'content://old'},{name:'a [Pole].jpg',uri:'content://new'},'[Pole]',source);
assert.equal(corrected[0].sourceUri,'content://new','upgrade older stored crop history folder reference');
assert.equal(corrected[0].sourceDirUri,source);
const app=fs.readFileSync(path.join(root,'App.js'),'utf8');
assert.equal((app.match(/ImageManipulator\.manipulateAsync\(/g)||[]).length,2,'use SDK 58 supported legacy API for decode and final crop');
assert(app.includes('uri:current.uri,')&&app.includes('inputUri:input.uri'),'crop renders original gallery image with a separate staged decoder input');
assert(!app.includes('ImageManipulator.ImageManipulator.manipulate('),'do not use contextual API responsible for regression');
assert(app.includes("setHistory(h=>historyAfterTagRename"),'tagging must NOT push history');
assert(app.includes('sourceDirUri:sourceUri'),'crop/ cut must preserve file URI in undo');
assert(app.includes('delayLongPress={450}'));
assert(app.includes('onLongPress={()=>{suppressUndoTap.current=true;setShowUndoPreview(true);}}'));
assert(app.includes('File ${op.type===\'copy\'?\'copied\':\'moved\'} to ${displayPath(target)}'));
console.log('PASS v15: crop SDK calls, undo previews, readable folders, tag-no-undo, URI history, long press wiring');
